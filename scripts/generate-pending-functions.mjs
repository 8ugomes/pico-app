// Generate ONLY new RPC signatures from the disposable PostgreSQL catalog.
// Does not contact or modify hosted databases or rewrite their canonical types.
import { readFile, writeFile } from 'node:fs/promises';
import { createTestDatabase } from '../tests/helpers/database.mjs';

const db = await createTestDatabase();
try {
  const { rows } = await db.query(`
    select p.proname, p.proargnames, p.pronargdefaults, p.proargmodes, p.proretset,
      array(select format_type(t,null) from unnest(p.proargtypes::oid[]) t) argument_types,
      array(select format_type(t,null) from unnest(p.proallargtypes) t) all_argument_types,
      format_type(p.prorettype,null) return_type
    from pg_proc p join pg_namespace n on n.oid=p.pronamespace
    where n.nspname='public' and (p.proname ~ '(^|_)(direct|push)_' or p.proname='export_account_messages')
    order by p.proname
  `);
  function type(name) {
    if (name.endsWith('[]')) return `${type(name.slice(0, -2))}[]`;
    if (['uuid', 'text', 'character varying', 'timestamp with time zone', 'timestamp without time zone'].includes(name)) return 'string';
    if (['integer', 'bigint', 'smallint', 'double precision', 'numeric'].includes(name)) return 'number';
    if (name === 'boolean') return 'boolean';
    if (['json', 'jsonb'].includes(name)) return 'Json';
    if (name === 'void') return 'undefined';
    throw Error(`Unhandled catalog type: ${name}`);
  }
  let result = '// Generated by node scripts/generate-pending-functions.mjs from local migrations.\n// Pending hosted regeneration; do not edit by hand.\nimport type { Json } from \'./database\';\n\nexport type PendingFunctions = {\n';
  for (const row of rows) {
    const args = row.argument_types.map((t, i) => `${row.proargnames[i]}${i >= row.argument_types.length - row.pronargdefaults ? '?' : ''}: ${type(t)}`).join('; ');
    const output = row.return_type === 'record'
      ? `{ ${row.all_argument_types.flatMap((t, i) => ['t', 'o', 'b'].includes(row.proargmodes[i]) ? [`${row.proargnames[i]}: ${type(t)}`] : []).join('; ')} }`
      : type(row.return_type);
    result += `  ${row.proname}: { Args: ${args ? `{ ${args} }` : 'Record<PropertyKey, never>'}; Returns: ${output}${row.proretset ? '[]' : ''} };\n`;
  }
  result += '};\n';
  const path = new URL('../src/types/pending-functions.ts', import.meta.url);
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8') !== result) throw Error('Pending RPC types differ from the migration catalog. Regenerate before committing.');
  } else await writeFile(path, result);
  console.log(`Verified ${rows.length} pending RPC signatures against the disposable migration catalog.`);
} finally { await db.close(); }
